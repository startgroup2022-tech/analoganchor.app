package com.analoganchor.app.util

import android.content.Context
import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Rect
import java.io.File
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

data class ReviewCardData(
    val clientName: String,
    val requestedAt: Long,
    val proofImagePath: String?,
    val beforeInsightsPath: String?,
    val proofNote: String?,
    val streakDays: Int,
    val requestsThisWeek: Int,
    val recoveryStatus: String,
    val activeFlags: Int
)

object ReviewCardRenderer {
    private const val WIDTH = 1200
    private const val HEIGHT = 1720
    private const val PADDING = 72f
    private const val CARD = 0xFF11191D.toInt()
    private const val BG = 0xFF0B1012.toInt()
    private const val CYAN = 0xFF7DEEFF.toInt()
    private const val WHITE = 0xFFF3F8FA.toInt()
    private const val SILVER = 0xFFA2AFB6.toInt()
    private const val AMBER = 0xFFF3B65C.toInt()

    fun renderToFile(context: Context, data: ReviewCardData): File {
        val bitmap = Bitmap.createBitmap(WIDTH, HEIGHT, Bitmap.Config.ARGB_8888)
        val canvas = Canvas(bitmap)
        canvas.drawColor(BG)

        val paint = Paint(Paint.ANTI_ALIAS_FLAG)
        paint.color = CARD
        canvas.drawRoundRect(40f, 40f, WIDTH - 40f, HEIGHT - 40f, 32f, 32f, paint)

        var y = 116f
        y = drawHeader(canvas, paint, y, data)
        y = drawSection(canvas, paint, y, "Proof Submitted")
        y = drawImageWithCaption(canvas, paint, y, data.proofImagePath, data.proofNote ?: "Physical proof attached.")
        y = drawSection(canvas, paint, y + 24f, "Strict-Mode Insights - Before")
        y = drawImageWithCaption(canvas, paint, y, data.beforeInsightsPath, "Before screenshot attached for context.")
        y = drawSection(canvas, paint, y + 24f, "Compliance Summary")

        val summaryLines = listOf(
            "Streak: ${data.streakDays} days",
            "Requests this week: ${data.requestsThisWeek} of 3",
            "Recovery status: ${data.recoveryStatus}",
            "Active behavior flags: ${data.activeFlags}"
        )
        summaryLines.forEach { line ->
            y = drawWrapped(canvas, paint, line, PADDING, y, 34f, WHITE, true)
            y += 14f
        }

        y = drawSection(canvas, paint, y + 28f, "Support Action")
        y = drawWrapped(
            canvas,
            paint,
            "Review this card, then check the strict-mode approval email. Analog Anchor provides custody context and records whether the user returns properly.",
            PADDING,
            y,
            31f,
            SILVER,
            false
        )

        y = HEIGHT - 132f
        drawWrapped(
            canvas,
            paint,
            "Generated by Analog Anchor - ${formatDate(System.currentTimeMillis())}",
            PADDING,
            y,
            28f,
            CYAN,
            true
        )

        return ProofFileStore.saveBitmapToCardFile(context, bitmap)
    }

    private fun drawHeader(
        canvas: Canvas,
        paint: Paint,
        startY: Float,
        data: ReviewCardData
    ): Float {
        var y = startY
        paint.color = CYAN
        paint.textSize = 48f
        paint.isFakeBoldText = true
        canvas.drawText("ANALOG ANCHOR", PADDING, y, paint)

        y += 50f
        paint.color = SILVER
        paint.textSize = 30f
        paint.isFakeBoldText = false
        canvas.drawText("Unlock review context", PADDING, y, paint)

        y += 46f
        paint.color = WHITE
        paint.textSize = 32f
        paint.isFakeBoldText = true
        canvas.drawText(data.clientName.ifBlank { "Client" }, PADDING, y, paint)

        y += 42f
        paint.color = SILVER
        paint.textSize = 28f
        paint.isFakeBoldText = false
        canvas.drawText(formatDate(data.requestedAt), PADDING, y, paint)

        y += 54f
        paint.color = 0x332B3A40
        canvas.drawRect(PADDING, y, WIDTH - PADDING, y + 2f, paint)
        return y + 56f
    }

    private fun drawSection(canvas: Canvas, paint: Paint, startY: Float, title: String): Float {
        paint.color = CYAN
        paint.textSize = 30f
        paint.isFakeBoldText = true
        canvas.drawText(title.uppercase(Locale.US), PADDING, startY, paint)
        return startY + 42f
    }

    private fun drawImageWithCaption(
        canvas: Canvas,
        paint: Paint,
        startY: Float,
        imagePath: String?,
        caption: String
    ): Float {
        val thumbSize = 170
        val rect = Rect(PADDING.toInt(), startY.toInt(), (PADDING + thumbSize).toInt(), (startY + thumbSize).toInt())
        paint.color = 0xFF172126.toInt()
        canvas.drawRoundRect(rect.left.toFloat(), rect.top.toFloat(), rect.right.toFloat(), rect.bottom.toFloat(), 20f, 20f, paint)

        val bitmap = imagePath?.let { BitmapFactory.decodeFile(it) }
        if (bitmap != null) {
            canvas.drawBitmap(bitmap, null, rect, paint)
        } else {
            paint.color = AMBER
            paint.textSize = 26f
            paint.isFakeBoldText = true
            canvas.drawText("IMAGE", rect.left + 38f, rect.top + 92f, paint)
        }

        return drawWrapped(
            canvas = canvas,
            paint = paint,
            text = caption,
            x = PADDING + thumbSize + 32f,
            startY = startY + 44f,
            textSize = 30f,
            color = SILVER,
            bold = false,
            maxWidth = WIDTH - PADDING - (PADDING + thumbSize + 32f)
        ).coerceAtLeast(startY + thumbSize + 10f)
    }

    private fun drawWrapped(
        canvas: Canvas,
        paint: Paint,
        text: String,
        x: Float,
        startY: Float,
        textSize: Float,
        color: Int,
        bold: Boolean,
        maxWidth: Float = WIDTH - (PADDING * 2f)
    ): Float {
        paint.color = color
        paint.textSize = textSize
        paint.isFakeBoldText = bold

        var y = startY
        val words = text.split(" ")
        var line = ""
        for (word in words) {
            val candidate = if (line.isEmpty()) word else "$line $word"
            if (paint.measureText(candidate) > maxWidth && line.isNotEmpty()) {
                canvas.drawText(line, x, y, paint)
                y += textSize + 14f
                line = word
            } else {
                line = candidate
            }
        }
        if (line.isNotEmpty()) {
            canvas.drawText(line, x, y, paint)
            y += textSize + 14f
        }
        return y
    }

    private fun formatDate(timestamp: Long): String {
        return SimpleDateFormat("MMM d, yyyy - h:mm a", Locale.getDefault()).format(Date(timestamp))
    }
}
